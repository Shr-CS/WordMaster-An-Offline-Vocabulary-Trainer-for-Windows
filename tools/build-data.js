'use strict';

// The lexicon is stored once; the seven catalogs refer to shared entries.
// A regular script also works offline in Electron and Android's asset WebView.
const fs = require('node:fs');
const path = require('node:path');
const data = path.join(__dirname, '../src/data');
const read = name => JSON.parse(fs.readFileSync(path.join(data, name), 'utf8'));
const lexicon = read('lexicon.json');
const catalog = read('catalog.json');
const examples = read('examples.json');
const notices = fs.readFileSync(path.join(__dirname, '../docs/THIRD_PARTY_NOTICES.txt'), 'utf8');
const keys = Object.keys(lexicon);
const indexes = new Map(keys.map((key, index) => [key, index]));
const entries = keys.map(key => {
  const { exampleId, ...word } = lexicon[key];
  return { ...word, ...(exampleId ? { exampleId } : {}) };
});
const levels = Object.fromEntries(Object.entries(catalog.levels).map(([id, level]) => {
  if (level.words.some(key => !indexes.has(key))) throw Error('Unknown entry in '+id);
  console.log(`${id.padEnd(8)} ${level.words.length} words (${level.basis})`);
  return [id, level.words.map(key => indexes.get(key))];
}));
const metadata = { version: catalog.version, levels: Object.fromEntries(Object.entries(catalog.levels).map(([id, level]) => [id, { basis: level.basis }])) };
const result = `/* Generated by tools/build-data.js from the reviewed lexicon and catalogs. */
window.WM_LEXICON = ${JSON.stringify(entries)};
window.WM_EXAMPLES = ${JSON.stringify(examples)};
window.WM_DATA_META = ${JSON.stringify(metadata)};
window.WM_DATA_NOTICES = ${JSON.stringify(notices)};
window.WM_DATA = Object.fromEntries(Object.entries(${JSON.stringify(levels)}).map(([level, indices]) => [level, indices.map(index => window.WM_LEXICON[index])]));
`;
fs.writeFileSync(path.join(data, 'words.js'), result);
console.log(`Built ${entries.length} shared entries, ${Object.values(levels).reduce((sum, values) => sum+values.length,0)} level records, ${(Buffer.byteLength(result)/1024).toFixed(1)} KB.`);
